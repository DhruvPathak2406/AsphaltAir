function setCpcbView(enabled) {
    cpcbDisplayed = enabled;
    const ipsOption = $("mapMode").querySelector('option[value="ips"]');
    ipsOption.disabled = enabled;
    if (enabled && $("mapMode").value === "ips") $("mapMode").value = "pm25";
    $("averageLabel").textContent = enabled ? "Mean reported PM2.5" : "Average PM2.5";
    $("averageDescription").textContent = enabled ? "Across available stations" : "Across loaded readings";
    $("peakLabel").textContent = enabled ? "Highest reported PM2.5" : "Peak PM2.5";
    $("peakDescription").textContent = enabled ? "Highest station average" : "Highest recorded reading";
    $("locationsLabel").textContent = enabled ? "CPCB Stations" : "Coordinate Groups";
    $("locationsDescription").textContent = enabled ? "Stations with available data" : "Unique measured locations";
    $("priorityTitle").textContent = enabled ? "CPCB Station Reports" : "Intervention Priorities";
    $("priorityDescription").textContent = enabled
        ? "Reported pollutant averages by station. IPS and speed are not calculated for this feed."
        : "Locations ranked by the priority analysis generated by Python.";
    $("speedNote").hidden = enabled;
    $("mapNote").textContent = enabled
        ? "Each point represents a CPCB station. Colours compare reported averages across displayed stations, not health thresholds. Boundaries are illustrative (up to 100 m), not measured pollution spread. Click a station for its reported time. Units are not specified in the API response."
        : localMapNote;
}

async function refreshCpcb(city, state, version) {
    if (!cpcbMode || version !== dataVersion) return;
    $("cpcbStatus").textContent = `Loading CPCB data for ${city}...`;
    try {
        const params = new URLSearchParams({ city, state });
        const response = await fetch(`/api/cpcb?${params}`, { cache: "no-store" });
        const data = await response.json();
        if (!response.ok) throw new Error(data.error || `Server returned ${response.status}`);
        if (!Array.isArray(data.stations)) throw new Error("The server returned invalid station data.");
        if (!data.stations.length) throw new Error("No usable station readings found for this city and state.");
        if (!cpcbMode || version !== dataVersion) return;
        setCpcbView(true);
        priorityRows = data.stations;
        cleanedRows = data.stations.map(row => ({
            latitude: row.latitude_group, longitude: row.longitude_group,
            "PM2.5": row.average_pm25
        }));
        cleanedCsv = null;
        $("downloadCleaned").disabled = true;
        uploadedCleanedRows = null;
        uploadedPriorityRows = null;
        uploadedHasTimestamp = null;
        updateTrendDownloadState();
        renderCleanedData();
        renderPriorityData();
        fitMapToData();
        $("status").textContent = `Showing CPCB station data for ${city}${state ? `, ${state}` : ""}. Local data updates are paused.`;
        $("cpcbStatus").textContent =
            `Loaded ${data.stations.length.toLocaleString()} stations; fetched at ${new Date().toLocaleTimeString()}. ` +
            "Source reports may be older: click a station for its reporting time. Refreshing every 10 minutes." +
            (data.skipped_records ? ` Skipped ${data.skipped_records} malformed records.` : "");
    } catch (error) {
        if (cpcbMode && version === dataVersion) {
            $("cpcbStatus").textContent =
                `CPCB update failed: ${error.message} Previously displayed data remains on screen; retrying in 10 minutes.`;
        }
    } finally {
        if (cpcbMode && version === dataVersion) {
            cpcbTimer = setTimeout(() => refreshCpcb(city, state, version), CPCB_REFRESH_MS);
        }
    }
}

