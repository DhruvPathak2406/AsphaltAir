function renderMap() {
    if (!priorityMap || !markerLayer || !boundaryLayer) return;

    const mode = $("mapMode").value;
    const metric = mode === "ips" ? "ips" : `average_${mode}`;
    const metricLabel = $("mapMode").selectedOptions[0].textContent;

    markerLayer.clearLayers();
    boundaryLayer.clearLayers();
    $("legendLow").textContent = mode === "ips" ? "Low (IPS ≤ 40)" : "Low (0–40% of range)";
    $("legendMedium").textContent = mode === "ips" ? "Medium (IPS > 40–70)" : "Medium (> 40–70% of range)";
    $("legendHigh").textContent = mode === "ips" ? "High (IPS > 70)" : "High (> 70% of range)";

    const validRows = priorityRows
        .map(row => ({
            row,
            coords: coordinatesOf(row),
            value: number(row, metric)
        }))
        .filter(item => item.coords && item.value != null);

    if (!validRows.length) {
        $("mapStatus").textContent =
            `No valid coordinates and ${metricLabel} values found in the priority data.`;

        return;
    }

    const values = validRows.map(item => item.value);
    const minValue = Math.min(...values);
    const maxValue = Math.max(...values);

    const equalValues = mode !== "ips" && minValue === maxValue;
    if (equalValues) {
        $("legendLow").textContent = "Low (not used)";
        $("legendMedium").textContent = "All values equal";
        $("legendHigh").textContent = "High (not used)";
    }

    const radii = illustrativeRadii(validRows);
    const markers = [];
    validRows.forEach((item, index) => {
        const row = item.row;
        const [lat, lon] = item.coords;
        const radius = radii[index];

        const priority = String(row.priority ?? "Unclassified").trim();
        const score = mode === "ips"
            ? item.value / 100
            : equalValues ? 0.5 : (item.value - minValue) / (maxValue - minValue);
        const level = score <= 0.4 ? "Low" : score <= 0.7 ? "Medium" : "High";
        const colour = priorityColour(level);

        const circle = L.circleMarker([lat, lon], {
            radius: 6,
            color: "#ffffff",
            fillColor: colour,
            fillOpacity: 0.95,
            opacity: 1,
            weight: 1.5
        });

        const popup = document.createElement("div");

        const title = document.createElement("strong");
        title.textContent = mode === "ips" ? `${level} priority` : `${level} relative value`;
        popup.appendChild(title);

        const details = [
            `Latitude: ${lat.toLocaleString(undefined, { maximumFractionDigits: 6 })}`,
            `Longitude: ${lon.toLocaleString(undefined, { maximumFractionDigits: 6 })}`,
            `Illustrative boundary radius: ${radius > 0 && radius < 0.01 ? "< 0.01" : display(radius)} m`
        ];
        if (cpcbDisplayed) {
            details.unshift(
                `Station: ${row.station_name}`,
                `Selected pollutant last reported: ${row.source_times?.[metric] || "Unavailable"} (source time)`,
                `${metricLabel}: ${item.value.toLocaleString(undefined, { maximumFractionDigits: 6 })} (units not provided)`
            );
        } else {
            details.push(
                `PM2.5 priority: ${priority}`,
                `IPS: ${display(number(row, "ips"))}`,
                `Average PM2.5: ${display(number(row, "average_pm25"))}`,
                `Maximum PM2.5: ${display(number(row, "max_pm25"))}`,
                `Readings: ${display(number(row, "readings"))}`,
                `Average device speed (km/h): ${display(number(row, "average_speed_kmh"))}`,
                `Speed/PM2.5 pairs: ${display(number(row, "speed_pm25_pairs"))}`,
                `Speed–PM2.5 correlation: ${display(number(row, "speed_pm25_correlation"))}`
            );
            if (mode !== "ips" && mode !== "pm25") {
                details.splice(4, 0, `${metricLabel}: ${item.value.toLocaleString(undefined, {
                maximumFractionDigits: 6
                })}`);
            }
        }

        details.forEach(detail => {
            const line = document.createElement("div");
            line.textContent = detail;
            popup.appendChild(line);
        });

        if (radius > 0) {
            L.circle([lat, lon], {
                radius,
                color: colour,
                fillColor: colour,
                fillOpacity: 0.15,
                opacity: 0.9,
                weight: 1
            }).bindPopup(popup.cloneNode(true)).addTo(boundaryLayer);
        }
        markers.push(circle.bindPopup(popup));
    });
    markers.forEach(circle => circle.addTo(markerLayer));

    $("mapStatus").textContent =
        `Showing ${validRows.length.toLocaleString()} locations. ` +
        (equalValues
            ? `All ${metricLabel} values are equal. `
            : `Circle colours represent ${metricLabel}. `) +
        "Click a point or boundary for details.";

    setTimeout(() => priorityMap.invalidateSize(), 100);
}

