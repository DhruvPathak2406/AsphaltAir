function initialiseMap() {
    if (priorityMap) return;

    if (typeof L === "undefined") {
        $("mapStatus").textContent =
            "Leaflet failed to load. Check your internet connection.";
        return;
    }

    priorityMap = L.map("priorityMap").setView(
        SURAT_CENTER,
        SURAT_ZOOM
    );

    
    L.tileLayer(
        "https://server.arcgisonline.com/ArcGIS/rest/services/World_Street_Map/MapServer/tile/{z}/{y}/{x}",
        {
            maxZoom: 19,
            attribution: "Tiles &copy; Esri"
        }
    ).addTo(priorityMap);


    boundaryLayer = L.layerGroup().addTo(priorityMap);
    markerLayer = L.layerGroup().addTo(priorityMap);

    $("mapStatus").textContent =
        "Map loaded. Load data with coordinates and PM2.5 to display hotspots.";

    $("resetMap").addEventListener("click", fitMapToData);

    $("mapMode").addEventListener("change", renderMap);

    setTimeout(() => priorityMap.invalidateSize(), 250);
}

function fitMapToData() {
    if (!priorityMap) return;
    const coordinates = (priorityRows.length ? priorityRows : cleanedRows)
        .map(coordinatesOf)
        .filter(coords => coords != null);
    if (coordinates.length) {
        priorityMap.fitBounds(L.latLngBounds(coordinates), { padding: [30, 30], maxZoom: 14 });
    } else {
        priorityMap.setView(SURAT_CENTER, SURAT_ZOOM);
    }
}

function renderCleanedData() {
    const pmValues = cleanedRows
        .map(row => number(row, "PM2.5"))
        .filter(value => value != null);
    const locations = new Set(
        cleanedRows
            .filter(row => number(row, "latitude") != null && number(row, "longitude") != null)
            .map(row => `${Number(row.latitude).toFixed(4)},${Number(row.longitude).toFixed(4)}`)
    );
    $("average").textContent = display(pmValues.length ? pmValues.reduce((a, b) => a + b, 0) / pmValues.length : null);
    $("peak").textContent = display(pmValues.length ? Math.max(...pmValues) : null);
    $("locations").textContent = locations.size.toLocaleString();
}

function renderPriorityData() {
    const body = $("priorityRows");
    body.replaceChildren();
    $("highPriority").textContent = cpcbDisplayed ? "—" : priorityRows.filter(row =>
        String(row.priority ?? "").trim().toLowerCase() === "high"
    ).length.toLocaleString();
    priorityRows.slice().sort((a, b) => (number(b, "ips") ?? -Infinity) - (number(a, "ips") ?? -Infinity))
        .slice(0, 100).forEach(row => {
            const tr = document.createElement("tr");
            [
                row.latitude_group ?? row.latitude,
                row.longitude_group ?? row.longitude,
                display(number(row, "average_pm25")),
                display(number(row, "readings")),
                display(number(row, "average_speed_kmh")),
                display(number(row, "speed_pm25_pairs")),
                display(number(row, "speed_pm25_correlation")),
                display(number(row, "ips"))
            ].forEach(value => {
                const td = document.createElement("td");
                td.textContent = value ?? "—";
                tr.appendChild(td);
            });
            const td = document.createElement("td");
            const badge = document.createElement("span");
            const priority = String(row.priority ?? "").trim();
            badge.className = `priority ${["High", "Medium", "Low"].find(level => level.toLowerCase() === priority.toLowerCase()) ?? ""}`;
            badge.textContent = priority || (cpcbDisplayed ? "Not scored" : "Unclassified");
            td.appendChild(badge);
            tr.appendChild(td);
            body.appendChild(tr);
        });
    if (!priorityRows.length) {
        const tr = document.createElement("tr");
        const td = document.createElement("td");
        td.colSpan = 9;
        td.textContent = "No priority groups. At least 10 PM2.5 readings per coordinate group are required.";
        tr.appendChild(td);
        body.appendChild(tr);
    }
    renderMap();
}

async function refreshLiveData() {
    if (manualMode) return;
    const version = dataVersion;
    try {
        const response = await fetch("/api/dashboard", { cache: "no-store" });
        const data = await response.json();
        if (!response.ok) throw new Error(data.error || `Server returned ${response.status}`);
        if (Number.isSafeInteger(data.upload_limit_bytes) && data.upload_limit_bytes > 0) {
            uploadLimitBytes = data.upload_limit_bytes;
            $("uploadLimit").textContent =
                `up to ${Math.floor(uploadLimitBytes / (1024 * 1024))} MB`;
        }
        if (manualMode || version !== dataVersion) return;
        setCpcbView(false);
        cleanedRows = data.cleaned;
        priorityRows = data.priority;
        renderCleanedData();
        renderPriorityData();
        if (!liveMapFitted && cleanedRows.some(row => coordinatesOf(row))) {
            fitMapToData();
            liveMapFitted = true;
        }
        $("status").textContent = `Local data connected: ${cleanedRows.length.toLocaleString()} readings, updated ${new Date().toLocaleTimeString()}.`;
    } catch (error) {
        console.error(error);
        if (!manualMode && version === dataVersion) {
            $("status").textContent = `Local data unavailable: ${error.message}. Start the server with python server.py.`;
        }
    }
}

